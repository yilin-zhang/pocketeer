//! Commands about pocketeer itself rather than a card or library: its
//! settings file and its reference. These are the ones that still work when
//! the config file is broken.

use std::{path::PathBuf, process::ExitCode};

use clap::{Command, CommandFactory};
use pocketeer_core::{Error, Result, config::Config, error::CODES};
use serde::Serialize;

use crate::human::table;
use crate::{
    cli::{Cli, ConfigCommand},
    context::Context,
    output::{Output, SCHEMA_VERSION},
};
use std::fmt::Write;

// ---------------------------------------------------------------------------
// config

pub fn config(ctx: &Context, out: &Output, cmd: ConfigCommand) -> ExitCode {
    match cmd {
        ConfigCommand::Path => out.emit(config_path(ctx), config_path_text),
        ConfigCommand::Get { key } => out.emit(config_get(ctx, key.as_deref()), config_show),
        ConfigCommand::Set { key, value } => {
            out.emit(config_set(ctx, &key, Some(&value)), config_show)
        }
        ConfigCommand::Unset { key } => out.emit(config_set(ctx, &key, None), config_show),
    }
}

#[derive(Debug, Serialize)]
pub struct ConfigPathReport {
    pub path: PathBuf,
    pub exists: bool,
}

pub fn config_path(ctx: &Context) -> Result<ConfigPathReport> {
    let path = ctx.config_path()?;
    Ok(ConfigPathReport {
        exists: path.is_file(),
        path,
    })
}

#[derive(Debug, Serialize)]
pub struct ConfigShowReport {
    pub path: PathBuf,
    /// Only the requested key when one was given.
    pub values: Vec<ConfigEntry>,
}

#[derive(Debug, Serialize)]
pub struct ConfigEntry {
    pub key: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub value: Option<String>,
}

fn show(config: &Config, path: PathBuf, only: Option<&str>) -> Result<ConfigShowReport> {
    let keys: Vec<&str> = match only {
        Some(k) => vec![k],
        None => pocketeer_core::config::KEYS.to_vec(),
    };
    let mut values = Vec::new();
    for key in keys {
        let mut value = config.get(key)?;
        if key == "github-token"
            && let Some(v) = &value
        {
            value = Some(format!("{}…", &v[..v.len().min(4)]));
        }
        values.push(ConfigEntry {
            key: key.to_string(),
            value,
        });
    }
    Ok(ConfigShowReport { path, values })
}

pub fn config_get(ctx: &Context, key: Option<&str>) -> Result<ConfigShowReport> {
    show(ctx.config()?, ctx.config_path()?, key)
}

/// `value: None` unsets the key.
pub fn config_set(ctx: &Context, key: &str, value: Option<&str>) -> Result<ConfigShowReport> {
    let path = ctx.config_path()?;
    let mut config = ctx.config()?.clone();
    config.set(key, value)?;
    config.save(&path)?;
    show(&config, path, Some(key))
}

// ---------------------------------------------------------------------------
// docs: the whole CLI reference, generated from the clap command tree so it
// can never drift from the real flags.

#[derive(Debug, Serialize)]
pub struct DocsReport {
    pub markdown: String,
    pub commands: Vec<String>,
    pub error_codes: Vec<ErrorCode>,
}

#[derive(Debug, Serialize)]
pub struct ErrorCode {
    pub code: &'static str,
    pub meaning: &'static str,
}

/// The hand-written part of the reference; the rest is generated from clap.
const CONVENTIONS: &str = include_str!("../../docs/conventions.md");

pub fn docs(path: &[String]) -> Result<DocsReport> {
    let mut root = Cli::command();
    root.build();

    // Narrow to a subtree if asked.
    let mut target: &mut Command = &mut root;
    let mut prefix = vec!["pocketeer".to_string()];
    for name in path {
        target = target
            .find_subcommand_mut(name)
            .ok_or_else(|| Error::ConfigKey {
                key: path.join(" "),
                known: vec!["run `pocketeer docs` for the full list".into()],
            })?;
        prefix.push(name.clone());
    }

    let mut md = String::new();
    let mut commands = Vec::new();
    if path.is_empty() {
        md.push_str(&format!(
            "# pocketeer CLI reference\n\nSchema version {SCHEMA_VERSION}. Generated by `pocketeer docs`.\n\n"
        ));
        md.push_str(CONVENTIONS);
        md.push_str("\n## Commands\n\n");
    } else {
        md.push_str(&format!("# {}\n\n", prefix.join(" ")));
    }
    walk(target, &prefix, &mut md, &mut commands);

    if path.is_empty() {
        md.push_str("## Error codes\n\n| code | meaning |\n|---|---|\n");
        for (code, meaning) in CODES {
            md.push_str(&format!("| `{code}` | {meaning} |\n"));
        }
    }

    Ok(DocsReport {
        markdown: md,
        commands,
        error_codes: CODES
            .iter()
            .map(|(code, meaning)| ErrorCode { code, meaning })
            .collect(),
    })
}

fn walk(cmd: &mut Command, prefix: &[String], md: &mut String, commands: &mut Vec<String>) {
    let full = prefix.join(" ");
    let has_children = cmd.get_subcommands().any(|c| c.get_name() != "help");
    md.push_str(&format!("### `{full}`\n\n```text\n"));
    md.push_str(cmd.render_long_help().to_string().trim_end());
    md.push_str("\n```\n\n");
    if !has_children {
        commands.push(full.clone());
    }
    let names: Vec<String> = cmd
        .get_subcommands()
        .map(|c| c.get_name().to_string())
        .filter(|n| n != "help")
        .collect();
    for name in names {
        let mut next = prefix.to_vec();
        next.push(name.clone());
        let sub = cmd.find_subcommand_mut(&name).expect("listed subcommand");
        walk(sub, &next, md, commands);
    }
}

// ---------------------------------------------------------------------------
// human-readable output

pub fn config_path_text(r: &ConfigPathReport) -> String {
    format!(
        "{}{}\n",
        r.path.display(),
        if r.exists { "" } else { "  (not created yet)" }
    )
}

pub fn config_show(r: &ConfigShowReport) -> String {
    let mut out = String::new();
    let rows: Vec<[String; 2]> = r
        .values
        .iter()
        .map(|e| {
            [
                e.key.clone(),
                e.value.clone().unwrap_or_else(|| "(unset)".into()),
            ]
        })
        .collect();
    table(&mut out, ["KEY", "VALUE"], &rows);
    let _ = writeln!(out, "\nConfig file: {}", r.path.display());
    out
}

pub fn docs_text(r: &DocsReport) -> String {
    r.markdown.clone()
}
